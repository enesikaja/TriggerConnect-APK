@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun GroupInviteScreen(
    groupId: String,
    onBack: () -> Unit,
    viewModel: GroupInviteViewModel = hiltViewModel(),
) {
    val state by viewModel.state.collectAsStateWithLifecycle()

    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text("Group invite") },
                navigationIcon = { IconButton(onClick = onBack) { Icon(Icons.AutoMirrored.Filled.ArrowBack, "Back") } },
            )
        },
    ) { padding ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(padding)
                .verticalScroll(rememberScrollState())
                .padding(20.dp),
            horizontalAlignment = Alignment.CenterHorizontally,
        ) {
            val invite = state.invitation
            if (invite != null) {
                QrImage(content = invite.token)
                Spacer(Modifier.height(16.dp))
                Text(
                    "This QR belongs only to this group and stays the same. " +
                        "Members scan it from the Scan tab. Maximum 100 people per group.",
                    style = MaterialTheme.typography.bodyMedium,
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                    textAlign = TextAlign.Center,
                )
            } else {
                PrimaryButton(
                    text = "Load group QR",
                    onClick = viewModel::generate,
                    loading = state.loading,
                    modifier = Modifier.fillMaxWidth(),
                )
            }
            state.error?.let {
                Spacer(Modifier.height(12.dp))
                Text(it, color = MaterialTheme.colorScheme.error, textAlign = TextAlign.Center)
            }
        }
    }
}

